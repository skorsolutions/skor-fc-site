import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {webcrypto} from 'node:crypto';
const c=vm.createContext({crypto:webcrypto});
vm.runInContext(fs.readFileSync('match-tiebreaks.js','utf8'),c);
const api=c.SKORTiebreaks;let id=0;const shot=(team,outcome)=>({id:String(++id),team,outcome});
let shots=[];
for(let i=0;i<3;i++)shots.push(shot('skor','scored'),shot('opponent','missed'));
assert.equal(api.summary(shots).winner,'skor','clinches before all ten kicks');
assert.throws(()=>api.summary([...shots,shot('skor','scored')]));
shots=[];for(let i=0;i<5;i++)shots.push(shot('opponent','scored'),shot('skor','scored'));
assert.equal(api.summary(shots,5,'opponent').sudden_death,true);
shots.push(shot('opponent','scored'));assert.equal(api.summary(shots,5,'opponent').winner,null,'first kick in sudden death is not a winner');
shots.push(shot('skor','missed'));assert.equal(api.summary(shots,5,'opponent').winner,'opponent');
assert.throws(()=>api.summary([shot('opponent','scored')],5,'skor'));
assert.equal(api.summary([shot('skor','scored'),shot('opponent','missed')],1).winner,'skor');
assert.equal(api.summary([],3).next_team,'skor');assert.throws(()=>api.summary([],0));assert.throws(()=>api.summary([{id:'',team:'skor',outcome:'scored'}]));assert.throws(()=>api.summary([{id:1,team:'skor',outcome:'scored'}]));
assert.equal(api.periodLabel('extra_second'),'Overtime · 2nd Half');
vm.runInContext(fs.readFileSync('post-match-entry.js','utf8'),c);
const draft=c.SKORPostMatch.createDraft({match:{id:'fixture',status:'final'},revision:'fixture',participants:[{player_key:'fixture',name:'Fixture',number:7}],events:[]});
c.SKORPostMatch.setCount(draft,'extra_first','fixture','skor_goal',2);c.SKORPostMatch.setCount(draft,'extra_second','fixture','skor_yellow_card',1);
assert.equal(c.SKORPostMatch.totals(draft).skor,2);assert.equal(c.SKORPostMatch.totals(draft,'extra_second').yellow,1);
assert.equal(c.SKORPostMatch.submission(draft).p_upserts.length,3);
const admin=fs.readFileSync('admin.html','utf8');
for(const a of ['end_regulation','start_extra_first_half','extra_halftime','start_extra_second_half','start_shootout'])assert.ok(admin.includes('data-clock-action="'+a+'"'));
const sql=fs.readFileSync('docs/sql/MATCH-TIEBREAKS.sql','utf8');
assert.ok(sql.includes('enable row level security'));assert.ok(sql.includes("errcode='40001'"));assert.ok(sql.includes('No more kicks can follow a decided shootout'));
assert.ok(!sql.includes('update public.player_match_attendance'));
console.log('Overtime periods and shootouts: configurable rounds, early clinch, both starting teams, sudden-death pairs, duplicate/invalid kicks, separate match-event totals and security contracts pass.');
